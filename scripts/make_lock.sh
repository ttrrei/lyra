#!/usr/bin/env bash
# 0009 D8: regenerate requirements.lock from a validated environment.
#
# Usage:
#   1. Build the dev venv:  python -m venv .venv
#   2. python -m pip install -e ".[dev,control]"   (+ ta-lib system lib)
#   3. Run the full test suite and confirm it is green.
#   4. bash scripts/make_lock.sh
#
# This is the project's single lock-file method (no separate
# requirements.txt — pyproject.toml is the only dependency source of
# truth). The lock is a complete pinned snapshot of the validated
# environment so CI installs bit-for-bit the same versions.
set -euo pipefail
cd "$(dirname "$0")/.."

PY=.venv/bin/python
if [ ! -x "$PY" ]; then
  echo "error: .venv/bin/python not found — build the dev venv first (see header)" >&2
  exit 1
fi
freeze() { "$PY" -m pip freeze | grep -vE "^-e "; }
VER="$("$PY" -c 'import sys;print(sys.version.split()[0])')"
DATE="$(date +%Y-%m-%d)"

RUNTIME="^(duckdb|pyarrow|pydantic|pydantic_core|annotated-types|typing-inspection|typing_extensions|PyYAML|pytz|typer|shellingham|rich|markdown-it-py|mdurl|Pygments|requests|certifi|charset-normalizer|idna|urllib3|TA-Lib|numpy)=="
DEV="^(pytest|iniconfig|pluggy|packaging|pyflakes|pandas|pandas-ta-classic|tulipy|python-dateutil|tzdata|annotated-doc)=="

{
  echo "# lyra - pinned environment (0009 D8: the single lock file; requirements.txt"
  echo "# is intentionally NOT a second source of truth)."
  echo "#"
  echo "# Generated by scripts/make_lock.sh from Python ${VER} (${DATE}). CI installs"
  echo "# from this file so the exact versions that passed the test suite are what"
  echo "# runs. Regenerate after any pyproject dependency change."
  echo "#"
  echo "# NOTE: TA-Lib 0.8.2 ships manylinux wheels (cp311/cp312), so CI installs it via pip."
  echo ""
  echo ""
  echo "# --- runtime (pyproject [project] dependencies + transitive) ---"
  freeze | grep -iE "$RUNTIME" | sort -f
  echo ""
  echo "# --- dev/test (pyproject [project.optional-dependencies] dev + control) ---"
  freeze | grep -iE "$DEV" | sort -f | grep -viE "^(numpy|pyarrow|pydantic)=="
} > requirements.lock

echo "wrote requirements.lock ($(grep -cE '==' requirements.lock) pinned packages)"
